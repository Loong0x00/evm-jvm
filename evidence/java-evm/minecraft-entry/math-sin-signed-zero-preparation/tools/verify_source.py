#!/usr/bin/env python3
"""Verify the exact one-image/one-native Math.sin signed-zero delta."""
from pathlib import Path
import hashlib
import json
import os
import re
import subprocess
import tempfile

here = Path(__file__).resolve().parent
stage = here.parent
root = here.parents[4]
baseline_stage = stage.parent / "sparse-primitive-array-checkpoint-preparation"
baseline_path = baseline_stage / "engine/MCEntryInterpreter.sol"
source_path = stage / "engine/MCEntryInterpreter.sol"
source = source_path.read_text()
baseline = baseline_path.read_text()
BASELINE_SHA256 = "d5825f990a369966d00054721e3646bf5b6f2b9c9f0f22371bca76a7d977e616"
assert hashlib.sha256(baseline.encode()).hexdigest() == BASELINE_SHA256


def block(text, start):
    at = text.index(start)
    end = text.find("\n    function ", at + 1)
    return text[at:end if end >= 0 else len(text)]


def image(text, name):
    body = block(text, "    function " + name + "(")
    values = re.findall(r'hex"([0-9a-f]+)"', body)
    assert len(values) == 1, (name, len(values))
    return bytes.fromhex(values[0])


def pascal_constant(name):
    overrides = {
        "ENUMSET": "EnumSet", "ITERABLE": "Iterable", "MATH": "Math",
        "RANDOM": "Random", "THREAD": "Thread", "THREAD_LOCAL": "ThreadLocal",
        "STACK_TRACE_ELEMENT": "StackTraceElement", "PRINT_STREAM": "PrintStream",
        "SECURITY_MANAGER": "SecurityManager",
    }
    tail = name.removeprefix("DBOOT_")
    return "_bootstrap" + overrides.get(tail, "".join(part.title() for part in tail.split("_")))


# The guest class is genuinely regenerated by the pinned Java 8 javac. Its full
# bytes, not a handwritten CP/Code patch, must equal the sole changed bootstrap
# image embedded in Solidity.
javac = Path("/usr/lib/jvm/java-8-openjdk/bin/javac")
assert javac.is_file()
with tempfile.TemporaryDirectory(prefix="java-diff-mc-math-sin-source-", dir=root / "build") as temp:
    out = Path(temp)
    source_file = stage / "bootstrap/java/lang/Math.java"
    subprocess.run([javac, "-source", "8", "-target", "8", "-g:none", "-d", out, source_file],
                   cwd=root, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    generated = (out / "java/lang/Math.class").read_bytes()

math_hex = stage / "bootstrap/java/lang/Math.class.hex"
math_sha_path = stage / "bootstrap/java/lang/Math.sha256"
assert math_hex.read_text().strip() == generated.hex()
math_sha = hashlib.sha256(generated).hexdigest()
assert math_sha_path.read_text().strip() == math_sha
assert image(source, "_bootstrapMath") == generated
assert len(generated) == 289
assert hashlib.sha256(image(baseline, "_bootstrapMath")).hexdigest() == "6092139a4281d1a0cbbaf5292ad894a4d494f5589a45605081ccb12ac3ed9861"
assert block(source, "    function _bootstrapRoot()") == block(baseline, "    function _bootstrapRoot()")

# Every bootstrap function except the Math leaf is byte-for-byte identical.
base_functions = set(re.findall(r"    function (_bootstrap\w+)\(", baseline))
new_functions = set(re.findall(r"    function (_bootstrap\w+)\(", source))
assert base_functions == new_functions
changed = sorted(name for name in base_functions if block(source, "    function " + name + "(") != block(baseline, "    function " + name + "("))
assert changed == ["_bootstrapMath"], changed

# Reconstruct all 97 ordered leaves from the actual Java class bytes. The few
# materialized-hash constants must agree with their corresponding images too.
root_block = block(source, "    function _bootstrapRoot()")
assignments = {int(index): rhs.strip() for index, rhs in re.findall(r"h\[(\d+)\]\s*=\s*([^;]+);", root_block)}
assert set(assignments) == set(range(97)) and len(assignments) == 97
leaves = []
for index in range(97):
    rhs = assignments[index]
    call = re.fullmatch(r"keccak256\((_bootstrap\w+)\(\)\)", rhs)
    constant = re.fullmatch(r"(DBOOT_[A-Z_]+)", rhs)
    if call:
        leaf = image(source, call.group(1))
    else:
        assert constant, (index, rhs)
        leaf_function = pascal_constant(constant.group(1))
        leaf = image(source, leaf_function)
        declaration = re.search(r"bytes32 private constant " + constant.group(1) + r"\s*=\s*([^;]+);", source)
        assert declaration, constant.group(1)
        expression = declaration.group(1).strip()
        if expression.startswith("hex\""):
            # Validate the materialized commitment against ordered Ethereum
            # Keccak after recomputing the full image list below.
            pass
        elif expression.startswith("keccak256(hex\""):
            constant_image = bytes.fromhex(expression[len('keccak256(hex"'):-2])
            assert constant_image == leaf, constant.group(1)
        else:
            raise AssertionError((constant.group(1), expression))
    leaves.append(leaf)

# Use the already-pinned local js-sha3 package for Ethereum Keccak and Solidity
# abi.encode(DBOOT, bytes32[97] dynamic array) ordering.
baseline_images = []
for index in range(97):
    rhs = assignments[index]
    call = re.fullmatch(r"keccak256\((_bootstrap\w+)\(\)\)", rhs)
    constant = re.fullmatch(r"(DBOOT_[A-Z_]+)", rhs)
    name = call.group(1) if call else pascal_constant(constant.group(1))
    baseline_images.append(image(baseline, name))

node = r'''const fs=require("fs"),{keccak256}=require("js-sha3");
const x=JSON.parse(fs.readFileSync(0,"utf8"));
const k=b=>keccak256(Buffer.from(b,"hex"));
const word=n=>Buffer.from(BigInt(n).toString(16).padStart(64,"0"),"hex");
const domain=keccak256(x.domain);
const derive=images=>{const hashes=images.map(v=>k(v));const encoded=Buffer.concat([Buffer.from(domain,"hex"),word(64),word(hashes.length),...hashes.map(h=>Buffer.from(h,"hex"))]);return {hashes,root:keccak256(encoded)}};
const current=derive(x.images),baseline=derive(x.baselineImages);
process.stdout.write(JSON.stringify({domain,...current,baselineRoot:baseline.root}));'''
env = {**os.environ, "NODE_PATH": str(root / "jvmevm/runtime/node_modules")}
result = subprocess.run(["node", "-e", node], input=json.dumps({
    "domain": "JVMEVM:MC-RANDOM-CLASS-P2:BOOTSTRAP:1",
    "images": [leaf.hex() for leaf in leaves],
    "baselineImages": [leaf.hex() for leaf in baseline_images],
}), text=True, capture_output=True, cwd=root, env=env, check=True)
commitment = json.loads(result.stdout)
# The inherited baseline pin 7e17... does not equal the root recomputed from
# the checked-in P2 Solidity expression and exact ordered images. Recompute
# the actual baseline source root before deriving the new image root; retain
# the discrepancy in the evidence instead of silently carrying the stale pin.
assert commitment["baselineRoot"] == "7d5bb2f602b85d8a6268549876df5b3811406bd54fd31429bea3d1ea11a19616"
assert commitment["hashes"][89] == "e354be66a6f5f6eecabb17b461000b63b90bea635f692a0cf0c36b6b5a688748"
assert commitment["hashes"][96] == "7c7093faf1a5f9610a8a179f48e634e451e0621862af33c14ec409dc8d6ef184"
assert source.count('bytes32 private constant DBOOT_MATH = hex"' + commitment["hashes"][89] + '";') == 1
for index, rhs in assignments.items():
    constant = re.fullmatch(r"(DBOOT_[A-Z_]+)", rhs)
    if not constant:
        continue
    expression = re.search(r"bytes32 private constant " + constant.group(1) + r"\s*=\s*([^;]+);", source).group(1).strip()
    if expression.startswith("hex\""):
        assert bytes.fromhex(expression[4:-1]).hex() == commitment["hashes"][index]

# Normalize only the approved native binding/signature/dispatch/error and the
# Math image+leaf hash. Exact equality protects sparse encoding, ABI, all other
# binding behavior, checkpoint codec, roots, and accounting from collateral edits.
normalized = source
normalized = normalized.replace(block(source, "    function _bootstrapMath()"), block(baseline, "    function _bootstrapMath()"), 1)
normalized = normalized.replace(
    'bytes32 private constant DBOOT_MATH = hex"' + commitment["hashes"][89] + '";',
    'bytes32 private constant DBOOT_MATH = hex"2d564544678da031e6acf47de0b92aceaeb777cc8829613397b3669ed4aeb478";', 1)
normalized = normalized.replace("    error MathSinProfileError(uint256 code, uint256 pc);\n", "", 1)
normalized = normalized.replace(
    "            // Binding18 preserves the measured deterministic sqrt surface;\n"
    "            // binding19 is only the measured signed-zero Math.sin leaf. Raw Math\n"
    "            // replacement is refused during preparation.\n",
    "            // Binding18 is the sole Math floating surface. Raw Math replacement\n"
    "            // is refused at preparation, and only this exact native declaration\n"
    "            // can reach the deterministic uint256 binary64 square-root kernel.\n", 1)
math_binding = '''            if (_equalsLiteral(c.data, nameOffset, nameLength, bytes("sin"))
                && _equalsLiteral(c.data, descriptorOffset, descriptorLength, bytes("(D)D"))) {
                return 19;
            }
'''
assert normalized.count(math_binding) == 1
normalized = normalized.replace(math_binding, "", 1)
normalized = normalized.replace("                && binding != 18 && binding != 19 && s.argumentKinds.length != 1)\n",
                                "                && binding != 18 && s.argumentKinds.length != 1)\n", 1)
normalized = normalized.replace("((binding == 18 || binding == 19) && (s.argumentKinds.length != 1",
                                "(binding == 18 && (s.argumentKinds.length != 1", 1)
math_dispatch = '''                    if (nativeBinding == 19) {
                        // This is not a partial trigonometry implementation. Only
                        // the two IEEE binary64 zero encodings are measured and
                        // supported; preserve their original sign bit exactly.
                        _requireKind(f.stack[base], KIND_DOUBLE, opPC);
                        uint64 raw = uint64(_payload(f.stack[base]));
                        if ((raw & 0x7fffffffffffffff) != 0) {
                            revert MathSinProfileError(1, opPC);
                        }
                        f.stack[base] = _packDouble(raw);
                        f.sp = base + 1;
                        continue;
                    }
'''
assert normalized.count(math_dispatch) == 1
normalized = normalized.replace(math_dispatch, "", 1)
assert normalized == baseline, "unexpected source changes beyond binding19 and Math leaf"

# Binding19 is exact global public-static native Math.sin(D)D. No String-local
# binding is changed. Its refusal error is intentionally distinct from CallError.
assert "return 19;" in source and "nativeBinding == 19" in source
assert "bytes(\"sin\")" in source and "bytes(\"(D)D\")" in source
assert "bytes32 private constant DBOOT_MATH" in source
assert "return 18;" in source and "nativeBinding == 18" in source
assert "binding != 19" in source and "binding == 18 || binding == 19" in source
assert "return 19;" in block(source, "    function _nativeBinding(")
assert "MathSinProfileError(1, opPC)" in source

old_leaves = []
for index in range(97):
    rhs = assignments[index]
    call = re.fullmatch(r"keccak256\((_bootstrap\w+)\(\)\)", rhs)
    constant = re.fullmatch(r"(DBOOT_[A-Z_]+)", rhs)
    name = call.group(1) if call else pascal_constant(constant.group(1))
    old_leaves.append(image(baseline, name))
assert all(leaves[i] == old_leaves[i] for i in range(97) if i != 89)

