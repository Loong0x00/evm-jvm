// Package s2a contains the artifact-loading surface for the versioned Stock S2a
// parser, metadata page, step module, and coordinator.
package s2a

import (
	"bytes"
	"embed"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"path"
	"strings"

	"github.com/ethereum/go-ethereum/accounts/abi"
	"github.com/ethereum/go-ethereum/jvmevm/stock"
)

const (
	S2aMetadataPage = "S2aMetadataPage"
	S2aClassParser  = "S2aClassParser"
	S2aStepModule   = "S2aStepModule"
	S2aCoordinator  = "S2aCoordinator"
)

// CompilerImmutableReference identifies a deployed-bytecode template range that
// solc fills from a constructor immutable.
type CompilerImmutableReference = stock.CompilerImmutableReference

//go:embed runtime/artifacts/*.json
var stockS2aArtifactFiles embed.FS

type stockS2aArtifactJSON struct {
	ContractName        string                                  `json:"contractName"`
	ABI                 json.RawMessage                         `json:"abi"`
	Bytecode            string                                  `json:"bytecode"`
	DeployedBytecode    string                                  `json:"deployedBytecode"`
	ImmutableReferences map[string][]CompilerImmutableReference `json:"immutableReferences"`
}

func stockS2aArtifactName(name string) error {
	switch name {
	case S2aMetadataPage, S2aClassParser, S2aStepModule, S2aCoordinator:
		return nil
	default:
		return fmt.Errorf("stock s2a: unknown artifact %q", name)
	}
}

func stockS2aReadArtifact(name string) (stockS2aArtifactJSON, error) {
	if err := stockS2aArtifactName(name); err != nil {
		return stockS2aArtifactJSON{}, err
	}
	filename := path.Join("runtime", "artifacts", name+".json")
	raw, err := fs.ReadFile(stockS2aArtifactFiles, filename)
	if err != nil {
		return stockS2aArtifactJSON{}, fmt.Errorf("stock s2a: required pinned artifact %s is unavailable: %w", name, err)
	}
	var doc stockS2aArtifactJSON
	if err := json.Unmarshal(raw, &doc); err != nil {
		return stockS2aArtifactJSON{}, fmt.Errorf("stock s2a: decode artifact %s: %w", name, err)
	}
	if doc.ContractName != name {
		return stockS2aArtifactJSON{}, fmt.Errorf("stock s2a: artifact %s has contractName %q", name, doc.ContractName)
	}
	if len(doc.ABI) == 0 || bytes.Equal(bytes.TrimSpace(doc.ABI), []byte("null")) {
		return stockS2aArtifactJSON{}, fmt.Errorf("stock s2a: artifact %s has no ABI", name)
	}
	return doc, nil
}

func stockS2aDecodeCode(name, field, encoded string) ([]byte, error) {
	encoded = strings.TrimPrefix(encoded, "0x")
	if encoded == "" {
		return nil, fmt.Errorf("stock s2a: artifact %s has empty %s", name, field)
	}
	if len(encoded)%2 != 0 {
		return nil, fmt.Errorf("stock s2a: artifact %s has odd-length %s", name, field)
	}
	code, err := hex.DecodeString(encoded)
	if err != nil {
		return nil, fmt.Errorf("stock s2a: artifact %s has invalid %s: %w", name, field, err)
	}
	return code, nil
}

// LoadArtifact loads one of the four pinned, embedded Stock S2a build artifacts.
// The accepted S0 ArtifactPage remains available only through stock.LoadArtifact.
// Missing S2a build output is a hard dependency error; no prototype or substitute
// bytecode is generated by this package.
func LoadArtifact(name string) (stock.Artifact, error) {
	doc, err := stockS2aReadArtifact(name)
	if err != nil {
		return stock.Artifact{}, err
	}
	contractABI, err := abi.JSON(bytes.NewReader(doc.ABI))
	if err != nil {
		return stock.Artifact{}, fmt.Errorf("stock s2a: parse ABI for %s: %w", name, err)
	}
	initCode, err := stockS2aDecodeCode(name, "bytecode", doc.Bytecode)
	if err != nil {
		return stock.Artifact{}, err
	}
	runtimeCode, err := stockS2aDecodeCode(name, "deployedBytecode", doc.DeployedBytecode)
	if err != nil {
		return stock.Artifact{}, err
	}
	if len(initCode) > 24*1024 {
		return stock.Artifact{}, fmt.Errorf("stock s2a: artifact %s initcode is %d bytes (limit %d)", name, len(initCode), 24*1024)
	}
	runtimeLimit := 12 * 1024
	if name == S2aClassParser {
		runtimeLimit = 16 * 1024
	}
	if len(runtimeCode) > runtimeLimit {
		return stock.Artifact{}, fmt.Errorf("stock s2a: artifact %s runtime is %d bytes (limit %d)", name, len(runtimeCode), runtimeLimit)
	}
	if err := stockS2aValidateImmutableReferences(name, uint64(len(runtimeCode)), doc.ImmutableReferences); err != nil {
		return stock.Artifact{}, err
	}
	return stock.Artifact{ABI: contractABI, InitCode: initCode, RuntimeCode: runtimeCode}, nil
}

// JavaFaultClass maps the only Java-fault kind in the frozen one-frame S2a
// profile. Callers must validate lifecycle and canonical fault state before
// using this label; arbitrary words are intentionally not decoded as Java.
func JavaFaultClass(kind uint8) (string, bool) {
	if kind == 1 {
		return "java.lang.ArithmeticException", true
	}
	return "", false
}

// CompilerImmutableReferences returns a defensive copy of pinned solc metadata.
// It is used by deployment tests to compare actual coordinator code with the
// compiler template without treating immutable placeholders as mismatches.
func CompilerImmutableReferences(name string) (map[string][]CompilerImmutableReference, error) {
	doc, err := stockS2aReadArtifact(name)
	if err != nil {
		return nil, err
	}
	runtimeCode, err := stockS2aDecodeCode(name, "deployedBytecode", doc.DeployedBytecode)
	if err != nil {
		return nil, err
	}
	if err := stockS2aValidateImmutableReferences(name, uint64(len(runtimeCode)), doc.ImmutableReferences); err != nil {
		return nil, err
	}
	out := make(map[string][]CompilerImmutableReference, len(doc.ImmutableReferences))
	for id, refs := range doc.ImmutableReferences {
		out[id] = append([]CompilerImmutableReference(nil), refs...)
	}
	return out, nil
}

func stockS2aValidateImmutableReferences(name string, runtimeLen uint64, refs map[string][]CompilerImmutableReference) error {
	type interval struct{ start, end uint64 }
	var occupied []interval
	for id, locations := range refs {
		if id == "" {
			return fmt.Errorf("stock s2a: artifact %s has an empty immutable id", name)
		}
		for _, ref := range locations {
			if ref.Length == 0 || ref.Start > runtimeLen || ref.Length > runtimeLen-ref.Start {
				return fmt.Errorf("stock s2a: artifact %s immutable %s range [%d,%d) is outside runtime length %d", name, id, ref.Start, ref.Start+ref.Length, runtimeLen)
			}
			current := interval{ref.Start, ref.Start + ref.Length}
			for _, previous := range occupied {
				if current.start < previous.end && previous.start < current.end {
					return fmt.Errorf("stock s2a: artifact %s has overlapping immutable ranges", name)
				}
			}
			occupied = append(occupied, current)
		}
	}
	if name == S2aCoordinator && len(occupied) == 0 {
		return errors.New("stock s2a: S2aCoordinator artifact has no compiler immutableReferences")
	}
	if name != S2aCoordinator && len(occupied) != 0 {
		return fmt.Errorf("stock s2a: stateless artifact %s unexpectedly has compiler immutableReferences", name)
	}
	return nil
}
